import fs from "node:fs/promises";
import { FileBlob, SpreadsheetFile } from "/Users/zhaoziru/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/@oai/artifact-tool/dist/artifact_tool.mjs";

const projectRoot = new URL("../", import.meta.url);
const workbookPath = new URL("data/frame-package-pricing.xlsx", projectRoot);
const outputPath = new URL("app/page/frame-package-pricing.generated.ts", projectRoot);

const workbook = await SpreadsheetFile.importXlsx(await FileBlob.load(decodeURIComponent(workbookPath.pathname)));
const sheet = workbook.worksheets.getItem("Frame Pricing");
const rows = sheet.getRange("A5:P31").values;
const packages = { six: {}, eight: {}, ten: {} };
const packageIds = {
  "6-piece package": "six",
  "8-piece package": "eight",
  "10-piece package": "ten",
};
const roundToTwo = (value) => Math.round(Number(value) * 100) / 100;

for (const row of rows) {
  const [packageName, , , , , , , material, , , , , originalPrice, newPackagePrice, sizeNote, sku] = row;
  const packageId = packageIds[packageName];
  if (!packageId || !material || !sku) continue;
  packages[packageId][sku] = {
    sku: String(sku),
    material: String(material),
    original: roundToTwo(originalPrice),
    price: roundToTwo(newPackagePrice),
    sizeNote: String(sizeNote ?? ""),
  };
}

const output = `// Generated by scripts/sync-frame-package-pricing.mjs. Do not edit manually.\nexport const packagePricing = ${JSON.stringify(packages, null, 2)} as const;\n`;
await fs.writeFile(outputPath, output, "utf8");
console.log(`Synced ${Object.values(packages).reduce((count, materials) => count + Object.keys(materials).length, 0)} package/material prices to ${outputPath.pathname}`);
